"""Builds dist/CscCoop-<version>.zip: BepInEx be.791 + the co-op plugin + a Russian README.

No game files: the interop assemblies are generated by BepInEx on the player's first launch.
Usage: python -I tools/make-package.py <version>
"""
import hashlib
import pathlib
import sys
import zipfile

root = pathlib.Path(__file__).resolve().parent.parent
version = sys.argv[1]
bepinex = root / "local" / "downloads" / "BepInEx-IL2CPP-be.791.zip"
expected = "bb1c510909b69522733791f3a0817a487379a52da6468a492f1c9c19b3ec6f9a"
if hashlib.sha256(bepinex.read_bytes()).hexdigest() != expected:
    sys.exit("BepInEx zip hash mismatch")
plugin_dir = root / "src" / "CscCoop" / "bin" / "Release" / "net6.0"
out = root / "dist" / f"CscCoop-{version}.zip"
out.parent.mkdir(exist_ok=True)

with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    with zipfile.ZipFile(bepinex) as b:
        for info in b.infolist():
            if not info.is_dir():
                z.writestr(info.filename, b.read(info))
    # Unity base libraries BepInEx otherwise downloads from unity.bepinex.dev on first launch. A friend's
    # download came out truncated ("End of Central Directory record could not be found") and BepInEx keeps
    # reusing a file that is already there, so ship the good copy (checked: 66 entries, zip test ok).
    libs = root / "local" / "game-copy" / "BepInEx" / "unity-libs" / "2021.3.45.zip"
    if hashlib.sha256(libs.read_bytes()).hexdigest() != "3cfde1613715c966cb8084087c37081ed5896871b39194d45a907a69dd7da9e5":
        sys.exit("unity-libs zip hash mismatch")
    z.write(libs, "BepInEx/unity-libs/2021.3.45.zip")
    for dll in ("CscCoop.dll", "CoopCore.dll"):
        z.write(plugin_dir / dll, f"BepInEx/plugins/CscCoop/{dll}")
    z.write(root / "dist-template" / "README-RU.txt", "README-RU.txt")

print(out, out.stat().st_size, hashlib.sha256(out.read_bytes()).hexdigest())
